def _build_minor() -> list[TarotCardDef]:
    cards: list[TarotCardDef] = []
    for suit_en, suit_ko in _SUITS:
        for rank_num, rank_en, rank_ko in _RANKS:
            up, rev = _MINOR_KEYWORDS[(suit_en, rank_num)]
            name_en = f"{rank_en} of {suit_en}"
            # 한글명: "완드 에이스" / "컵 7" / "소드 퀸"
            name_ko = f"{suit_ko} {rank_ko}"
            cards.append(
                TarotCardDef(
                    name_en=name_en,
                    name_ko=name_ko,
                    arcana="minor",
                    upright=up,
                    reversed=rev,
                    number=rank_num,
                    suit=suit_ko,
                )
            )
    return cards


_MINOR: list[TarotCardDef] = _build_minor()

