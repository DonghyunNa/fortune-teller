from dataclasses import dataclass, field
from typing import Optional


@dataclass(frozen=True)
class TarotCardDef:
    name_en: str
    name_ko: str
    arcana: str  # "major" | "minor"
    upright: list[str]  # 정방향 키워드 3~5개
