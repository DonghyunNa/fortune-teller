    suit: Optional[str] = None  # 마이너만: 완드/컵/소드/펜타클

    def keywords_for(self, is_reversed: bool) -> list[str]:
        """현재 방향 기준 키워드 리스트."""
        return list(self.reversed if is_reversed else self.upright)


